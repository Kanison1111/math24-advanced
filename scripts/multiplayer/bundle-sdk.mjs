// Reproducible local browser SDK: npm ci verifies locked dependency integrity.
import {build} from 'esbuild';
import {readFile,writeFile,readdir} from 'node:fs/promises';
import {join} from 'node:path';
const check=process.argv.includes('--check');
const result=await build({entryPoints:['scripts/multiplayer/sdk-entry.mjs'],outfile:'multiplayer/vendor/supabase.mjs',
  bundle:true,write:false,supported:{'template-literal':false},platform:'browser',format:'esm',target:'es2022',minify:true,metafile:true,legalComments:'eof',
  banner:{js:'// Generated by npm run build:client. See THIRD_PARTY_LICENSES.txt and package-lock.json.'}});
const modules=new Set(Object.keys(result.metafile.inputs).map(path=>path.match(/^node_modules\/((?:@[^/]+\/)?[^/]+)/)?.[1]).filter(Boolean));
const licenses=[];
for(const name of [...modules].sort()) {
  const directory=join('node_modules',name),pkg=JSON.parse(await readFile(join(directory,'package.json'),'utf8'));
  const license=(await readdir(directory)).find(file=>/^licen[sc]e(?:\.(?:md|txt))?$/i.test(file));
  if(!license)throw Error('Missing vendored license for '+name);
  licenses.push(`${name}@${pkg.version}\n${(await readFile(join(directory,license),'utf8')).replace(/\r\n/g,'\n')}`);
}
for(const [path,content]of [
  ['multiplayer/vendor/supabase.mjs',result.outputFiles[0].text],
  ['multiplayer/vendor/THIRD_PARTY_LICENSES.txt',licenses.join('\n\n'+'='.repeat(72)+'\n\n')+'\n'],
]) {
  if(check) {if(await readFile(path,'utf8')!==content)throw Error('Vendored SDK drift: '+path);}
  else await writeFile(path,content);
}
console.log(check?'Vendored SDK matches locked inputs':'Built local browser SDK with required licenses');
